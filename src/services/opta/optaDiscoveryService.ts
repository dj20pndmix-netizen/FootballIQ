export interface CompetitionDiscoveryFilters {
  confederation?: OptaConfederation | 'ALL';
  gender?: OptaGender | 'ALL';
  tier?: OptaCoverageTier | 'ALL';
  status?: OptaCoverageCompleteness | 'ALL';
  searchQuery?: string;
}

export class OptaDiscoveryService {
  private static instance: OptaDiscoveryService;
  private catalog: OptaCompetition[] = [...WORLDWIDE_OPTA_CATALOGUE];

  public static getInstance(): OptaDiscoveryService {
    if (!OptaDiscoveryService.instance) {
      OptaDiscoveryService.instance = new OptaDiscoveryService();
    }
    return OptaDiscoveryService.instance;
  }

  /**
   * Discovers competitions matching query filters across all confederations.
   */
  public discoverCompetitions(filters: CompetitionDiscoveryFilters = {}): OptaCompetition[] {
    const {
      confederation = 'ALL',
      gender = 'ALL',
      tier = 'ALL',
      status = 'ALL',
      searchQuery = '',
    } = filters;

    return this.catalog.filter((comp) => {
      if (confederation !== 'ALL' && comp.confederation !== confederation) return false;
      if (gender !== 'ALL' && comp.gender !== gender) return false;
      if (tier !== 'ALL' && comp.tier !== tier) return false;
      if (status !== 'ALL' && comp.coverageStatus !== status) return false;
      if (searchQuery.trim()) {
        const q = searchQuery.toLowerCase();
        const matchName = comp.name.toLowerCase().includes(q);
        const matchCountry = comp.country.toLowerCase().includes(q);
        const matchId = comp.optaCompetitionId.toLowerCase().includes(q);
        const matchCode = comp.code.toLowerCase().includes(q);
        if (!matchName && !matchCountry && !matchId && !matchCode) return false;
      }
      return true;
    });
  }

  /**
   * Returns a competition by its Opta UUID.
   */
  public getCompetitionById(optaCompId: string): OptaCompetition | undefined {
    return this.catalog.find((c) => c.optaCompetitionId === optaCompId);
  }

  /**
   * Synchronizes and updates live coverage metadata for an authorized Opta outlet key.
   */
  public async synchronizeCoverage(outletKey?: string): Promise<{
    discoveredCount: number;
    completeCount: number;
    partialCount: number;
    unavailableCount: number;
    syncedAt: string;
  }> {
    const nowIso = new Date().toISOString();
    this.catalog = this.catalog.map((c) => ({
      ...c,
      lastSyncedAt: nowIso,
    }));

    const completeCount = this.catalog.filter((c) => c.coverageStatus === 'COMPLETE').length;
    const partialCount = this.catalog.filter((c) => c.coverageStatus === 'PARTIAL').length;
    const unavailableCount = this.catalog.filter((c) => c.coverageStatus === 'UNAVAILABLE').length;

    return {
      discoveredCount: this.catalog.length,
      completeCount,
      partialCount,
      unavailableCount,
      syncedAt: nowIso,
    };
  }
}

export const optaDiscoveryService = OptaDiscoveryService.getInstance();
