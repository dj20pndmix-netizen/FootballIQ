/**
 * Normalizes a team name for reliable dictionary lookups.
 * Strips diacritics, lowercase, trims punctuation and common prefixes.
 */
export function normalizeTeamName(rawName: string): string {
  if (!rawName) return '';
  return rawName
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/^(fc|afc|cf|cd|sc|ac|rc|as|rsc|krc)\s+/i, '')
    .replace(/\s+(fc|afc|cf|cd|sc|ac|rc|uanl|hd)$/i, '')
    .trim();
}

/**
 * Retrieves authentic team badge metadata.
 * Always returns a valid TeamBadgeData object, falling back to an
 * algorithmic heraldic colorway and shortcode if an obscure team is encountered.
 */
export function getTeamBadge(rawName: string, country?: string): TeamBadgeData {
  if (!rawName) {
    return {
      name: 'Unknown Team',
      shortCode: 'FC',
      badgeUrl: '',
      primaryColor: '#10B981',
      secondaryColor: '#047857',
      symbol: 'Football Crest',
      badgeType: 'club',
    };
  }

  const normalized = normalizeTeamName(rawName);
  const directMatch = TEAM_BADGES_REGISTRY[rawName.toLowerCase()] || TEAM_BADGES_REGISTRY[normalized];

  if (directMatch) {
    return directMatch;
  }

  // Check partial key matching
  for (const [key, data] of Object.entries(TEAM_BADGES_REGISTRY)) {
    if (normalized.includes(key) || key.includes(normalized)) {
      return data;
    }
  }

  // Algorithmic heraldic crest generation
  const words = rawName.trim().split(/\s+/);
  const shortCode = words.length >= 3
    ? (words[0][0] + words[1][0] + words[2][0]).toUpperCase()
    : words.length === 2
    ? (words[0].slice(0, 2) + words[1][0]).toUpperCase()
    : rawName.slice(0, 3).toUpperCase();

  // Hash-based deterministic color palette
  let hash = 0;
  for (let i = 0; i < rawName.length; i++) {
    hash = (hash << 5) - hash + rawName.charCodeAt(i);
    hash |= 0;
  }
  const hues = [210, 345, 145, 45, 275, 195, 25, 170];
  const primaryHue = hues[Math.abs(hash) % hues.length];
  const secondaryHue = (primaryHue + 40) % 360;

  return {
    name: rawName,
    shortCode,
    badgeUrl: '',
    primaryColor: `hsl(${primaryHue}, 80%, 45%)`,
    secondaryColor: `hsl(${secondaryHue}, 70%, 35%)`,
    symbol: `${shortCode} Crest`,
    badgeType: country && ['Uganda', 'Botswana', 'Kosovo', 'Israel', 'England', 'Spain', 'France', 'Germany'].includes(country)
      ? 'national'
      : 'club',
  };
}
